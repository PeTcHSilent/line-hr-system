-- เดิมระบบ "เตือนอย่างเดียว" — ยื่นเกินสิทธิ์ได้ แล้วค่อยให้หัวหน้าตัดสินใจ
-- นโยบายใหม่: ประเภทไหนใช้ครบแล้ว ยื่นประเภทนั้นไม่ได้อีก
--
-- ❗ ทำไมเป็นสวิตช์รายประเภท ไม่ใช่บล็อกทุกประเภทรวด
--   "ลาป่วย 30 วัน" ตามกฎหมายไม่ใช่เพดานการลา แต่เป็นเพดาน "วันที่ได้เงิน"
--   พ.ร.บ.คุ้มครองแรงงาน ม.32 ให้ลูกจ้างลาป่วยได้ "เท่าที่ป่วยจริง"
--   ส่วน ม.57 กำหนดว่าจ่ายค่าจ้างให้ไม่เกิน 30 วันทำงานต่อปี
--
--   ถ้าบล็อกลาป่วยที่วันที่ 31 พนักงานที่ป่วยจริงจะยื่นใบลาไม่ได้
--   กลายเป็น "ขาดงาน" ซึ่งเป็นเหตุทางวินัยและผิดกฎหมาย
--   บริษัทเสี่ยงมากกว่าที่ได้ จึงเปิดให้ยื่นต่อ (แต่ยังเตือนว่าเกินสิทธิ์)
--
--   ลากิจ/ลาพักผ่อน เป็นสวัสดิการที่มีเพดานจริง → บล็อกได้
--
-- เปลี่ยนทีหลังได้จากหน้าเว็บ: ตั้งค่า HR → ประเภทการลา
-- ══════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE leave_types
  ADD COLUMN IF NOT EXISTS block_when_exceeded BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN leave_types.block_when_exceeded IS
  'TRUE = ใช้สิทธิ์ครบแล้วยื่นลาประเภทนี้ไม่ได้ / FALSE = ยื่นได้แต่ขึ้นเตือนว่าเกินสิทธิ์';

-- ── เปิดให้ยื่นต่อได้ เฉพาะประเภทที่เป็นสิทธิตามกฎหมาย ──
UPDATE leave_types
SET    block_when_exceeded = FALSE
WHERE  name ILIKE '%ป่วย%'          -- ม.32 ลาได้เท่าที่ป่วยจริง
   OR  name ILIKE '%คลอด%'          -- ม.41 สิทธิตามกฎหมาย
   OR  name ILIKE '%ไม่รับเงิน%'    -- ไม่มีโควตาอยู่แล้ว
   OR  name ILIKE '%ไม่ได้รับค่าจ้าง%';

COMMIT;
