-- นโยบายบริษัท: พนักงานที่ยังทดลองงานยังไม่ได้สวัสดิการวันลา
--   ต้องแจ้งลาเป็น "ลาไม่รับเงิน" แทน
--
-- ทำไมเก็บเป็นคอลัมน์ ไม่ใช่เขียนชื่อประเภทลาไว้ในโค้ด:
--   - ชื่อประเภทลาแก้ได้จากหน้าเว็บ ถ้า hardcode ไว้แล้วมีคนเปลี่ยนชื่อ
--     "ลาพักร้อน" เป็น "ลาพักผ่อนประจำปี" เงื่อนไขจะเงียบหายไปทันที
--   - บริษัทอาจเพิ่มประเภทลาใหม่ทีหลัง จะได้ตั้งค่าเองได้ไม่ต้องแก้โค้ด
--
-- ❗ ค่าเริ่มต้นเป็น TRUE (ลาได้) โดยตั้งใจ
--    ประเภทลาที่เพิ่มใหม่ในอนาคตจะไม่ถูกบล็อกโดยไม่รู้ตัว
-- ══════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE leave_types
  ADD COLUMN IF NOT EXISTS allowed_during_probation BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN leave_types.allowed_during_probation IS
  'FALSE = พนักงานที่ยังทดลองงานยื่นลาประเภทนี้ไม่ได้';

-- ปิดเฉพาะสวัสดิการวันลาของบริษัท
UPDATE leave_types
SET    allowed_during_probation = FALSE
WHERE  name IN ('ลาพักร้อน', 'ลากิจ');

-- ── ที่ "ไม่" ปิด และเหตุผล ──────────────────────────────────
--   ลาป่วย   — เป็นสิทธิตามกฎหมายตั้งแต่วันแรกที่เริ่มงาน
--   ลาคลอด   — เป็นสิทธิตามกฎหมายเช่นกัน
--   ลาไม่รับเงิน — คือทางที่ให้พนักงานทดลองงานใช้แทน
--
-- หากต้องการเปลี่ยนภายหลัง แก้ได้จากหน้าเว็บ: ตั้งค่า HR → ประเภทการลา
-- ไม่ต้องแก้ไฟล์นี้หรือ deploy ใหม่

COMMIT;
