--   - รหัสพนักงานแก้ได้จากหน้าเว็บ ถ้ามีคนเปลี่ยนรหัส เงื่อนไขจะเงียบหายไป
--     โดยไม่มีอะไรเตือน (บั๊กประเภทที่หายากที่สุด)
--   - HR ตั้งค่าเองได้จากหน้าแก้ไขพนักงาน
--
-- ❗ ค่าเริ่มต้นเป็น TRUE (แจ้งเตือน) โดยตั้งใจ
--    พนักงานใหม่ต้องได้รับแจ้งเตือนเสมอ ไม่ใช่เงียบเพราะลืมตั้งค่า
--
-- ❗ ยกเว้นเฉพาะ "การแจ้งเตือนให้ไปเช็คอิน/เช็คเอาท์" เท่านั้น
--    ไม่กระทบการบันทึกเวลาจริง รายงาน หรือการคำนวณเงินเดือน
--    ผู้บริหารยังเช็คอินได้ปกติ และยังอยู่ในรายงานเข้า-ออกงานทุกฉบับ
-- ══════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE employees
  ADD COLUMN IF NOT EXISTS notify_attendance BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN employees.notify_attendance IS
  'FALSE = ไม่ส่งแจ้งเตือนเช็คอิน/เช็คเอาท์ให้คนนี้ (เช่น ผู้บริหาร) — ไม่กระทบการบันทึกเวลาจริง';

-- ปิดแจ้งเตือนสำหรับรหัสผู้บริหาร
UPDATE employees
SET    notify_attendance = FALSE
WHERE  employee_code IN ('TK0000', 'TK0001', 'TK0002', 'TK0003');

COMMIT;

